"""Generate fabric/big/rtl/bwprobe_axi.v — AXI-Lite control + NM read masters.

Plain Verilog-2001 on purpose: Vivado block-design module references infer one
AXI interface per `mN_axi_*` port group, and port lists can't be generated with
`generate`, so this script writes them out.

    python -m fabric.big.gen_bwprobe_top [--nm 6]

Register map (32-bit, byte offsets; must match board/pl_bwprobe.py):
  0x00 CTRL    W  bit0 go, bit1 soft reset
  0x04 STATUS  R  [NM-1:0] done mask, bit16 busy
  0x08 ENABLE  RW [NM-1:0]
  0x0C BASE_LO RW   0x10 BASE_HI RW  (master i reads from BASE + i*STRIDE)
  0x14 STRIDE  RW  bytes
  0x18 BEATS   RW  16-byte beats per master
  0x1C BURST   RW  beats per burst (pow2, 1..256)
  0x20 MAXOUT  RW  bursts in flight per master
  0x24 NIDS    RW  ARID rotation count (1..64)
  0x28 GCYC_LO R   0x2C GCYC_HI R   go -> all enabled masters done
  0x30 IDCODE  R   "BWPR"
  0x34 NM      R
  0x38 AXPARAM RW  [3:0] arqos, [7:4] arcache
  0x3C STEP    RW  bytes between a master's successive bursts (0 = contiguous)
  0x100 + i*0x20: +0 cyc_lo +4 cyc_hi +8 beats +C rresp errors +10..+1C xsum[31:0..127:96]
"""
from __future__ import annotations

import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent

M_PORTS = [  # (dir, width, name)
    ("output", "IDW", "awid"), ("output", "AW", "awaddr"), ("output", 8, "awlen"),
    ("output", 3, "awsize"), ("output", 2, "awburst"), ("output", 1, "awlock"),
    ("output", 4, "awcache"), ("output", 3, "awprot"), ("output", 4, "awqos"),
    ("output", 1, "awvalid"), ("input", 1, "awready"),
    ("output", 128, "wdata"), ("output", 16, "wstrb"), ("output", 1, "wlast"),
    ("output", 1, "wvalid"), ("input", 1, "wready"),
    ("input", "IDW", "bid"), ("input", 2, "bresp"), ("input", 1, "bvalid"),
    ("output", 1, "bready"),
    ("output", "IDW", "arid"), ("output", "AW", "araddr"), ("output", 8, "arlen"),
    ("output", 3, "arsize"), ("output", 2, "arburst"), ("output", 1, "arlock"),
    ("output", 4, "arcache"), ("output", 3, "arprot"), ("output", 4, "arqos"),
    ("output", 1, "arvalid"), ("input", 1, "arready"),
    ("input", "IDW", "rid"), ("input", 128, "rdata"), ("input", 2, "rresp"),
    ("input", 1, "rlast"), ("input", 1, "rvalid"), ("output", 1, "rready"),
]


def w(width):
    if width == 1:
        return ""
    if isinstance(width, str):
        return f"[{width}-1:0] "
    return f"[{width - 1}:0] "


def gen(nm: int) -> str:
    busifs = ":".join(["S_AXI"] + [f"m{i}_axi" for i in range(nm)])
    L = []
    a = L.append
    a("// GENERATED by fabric/big/gen_bwprobe_top.py — do not edit by hand.")
    a("// bwprobe_axi: AXI-Lite control + %d AXI4 read masters (doc 10 R0)." % nm)
    a("`timescale 1ns / 1ps")
    a("")
    a("module bwprobe_axi #(")
    a("    parameter integer C_S_AXI_ADDR_WIDTH = 10,")
    a("    parameter integer AW  = 49,")
    a("    parameter integer IDW = 6")
    a(") (")
    a(f'    (* X_INTERFACE_PARAMETER = "ASSOCIATED_BUSIF {busifs}, ASSOCIATED_RESET S_AXI_ARESETN" *)')
    a("    input  wire                          S_AXI_ACLK,")
    a("    input  wire                          S_AXI_ARESETN,")
    a("    input  wire [C_S_AXI_ADDR_WIDTH-1:0] S_AXI_AWADDR,")
    a("    input  wire [2:0]                    S_AXI_AWPROT,")
    a("    input  wire                          S_AXI_AWVALID,")
    a("    output reg                           S_AXI_AWREADY,")
    a("    input  wire [31:0]                   S_AXI_WDATA,")
    a("    input  wire [3:0]                    S_AXI_WSTRB,")
    a("    input  wire                          S_AXI_WVALID,")
    a("    output reg                           S_AXI_WREADY,")
    a("    output reg  [1:0]                    S_AXI_BRESP,")
    a("    output reg                           S_AXI_BVALID,")
    a("    input  wire                          S_AXI_BREADY,")
    a("    input  wire [C_S_AXI_ADDR_WIDTH-1:0] S_AXI_ARADDR,")
    a("    input  wire [2:0]                    S_AXI_ARPROT,")
    a("    input  wire                          S_AXI_ARVALID,")
    a("    output reg                           S_AXI_ARREADY,")
    a("    output reg  [31:0]                   S_AXI_RDATA,")
    a("    output reg  [1:0]                    S_AXI_RRESP,")
    a("    output reg                           S_AXI_RVALID,")
    a("    input  wire                          S_AXI_RREADY,")
    ports = []
    for i in range(nm):
        for d, wd, n in M_PORTS:
            ports.append(f"    {d:6s} wire {w(wd)}m{i}_axi_{n}")
    a(",\n".join(ports))
    a(");")
    a(f"    localparam integer NM = {nm};")
    a("""    wire clk = S_AXI_ACLK;
    wire aresetn = S_AXI_ARESETN;

    // ---------------- AXI-Lite register file ----------------
    reg [C_S_AXI_ADDR_WIDTH-1:0] awaddr;
    wire wr_en_axi = S_AXI_AWVALID & S_AXI_WVALID & ~S_AXI_BVALID;
    reg        go_pulse, soft_reset;
    reg [NM-1:0] enable;
    reg [31:0] base_lo, base_hi, stride, beats, burst_r, maxout_r, nids_r, axparam, step_r;

    always @(posedge clk) begin
        if (!aresetn) begin
            S_AXI_AWREADY <= 1'b0; S_AXI_WREADY <= 1'b0;
            S_AXI_BVALID  <= 1'b0; S_AXI_BRESP <= 2'b00; awaddr <= 0;
            go_pulse <= 1'b0; soft_reset <= 1'b0; enable <= 0;
            base_lo <= 0; base_hi <= 0; stride <= 0; beats <= 0;
            burst_r <= 32'd16; maxout_r <= 32'd8; nids_r <= 32'd1; axparam <= 32'h30; step_r <= 0;
        end else begin
            go_pulse <= 1'b0; soft_reset <= 1'b0;
            if (wr_en_axi && !S_AXI_AWREADY) begin
                S_AXI_AWREADY <= 1'b1; S_AXI_WREADY <= 1'b1; awaddr <= S_AXI_AWADDR;
            end else begin
                S_AXI_AWREADY <= 1'b0; S_AXI_WREADY <= 1'b0;
            end
            if (S_AXI_AWREADY) begin
                case (awaddr[C_S_AXI_ADDR_WIDTH-1:2])
                    8'h00: begin go_pulse <= S_AXI_WDATA[0]; soft_reset <= S_AXI_WDATA[1]; end
                    8'h02: enable   <= S_AXI_WDATA[NM-1:0];
                    8'h03: base_lo  <= S_AXI_WDATA;
                    8'h04: base_hi  <= S_AXI_WDATA;
                    8'h05: stride   <= S_AXI_WDATA;
                    8'h06: beats    <= S_AXI_WDATA;
                    8'h07: burst_r  <= S_AXI_WDATA;
                    8'h08: maxout_r <= S_AXI_WDATA;
                    8'h09: nids_r   <= S_AXI_WDATA;
                    8'h0E: axparam  <= S_AXI_WDATA;
                    8'h0F: step_r   <= S_AXI_WDATA;
                    default: ;
                endcase
                S_AXI_BVALID <= 1'b1; S_AXI_BRESP <= 2'b00;
            end else if (S_AXI_BVALID && S_AXI_BREADY) begin
                S_AXI_BVALID <= 1'b0;
            end
        end
    end

    // ---------------- masters ----------------
    wire          rst = ~aresetn | soft_reset;
    wire [63:0]   base64 = {base_hi, base_lo};
    wire [NM-1:0] done_v;
    wire [63:0]   cyc_v  [0:NM-1];
    wire [31:0]   rcv_v  [0:NM-1];
    wire [31:0]   err_v  [0:NM-1];
    wire [127:0]  xs_v   [0:NM-1];
""")
    for i in range(nm):
        a(f"""    axi_rd_probe #(.AW(AW), .IDW(IDW)) u_m{i} (
        .clk(clk), .rst(rst), .go(go_pulse), .enable(enable[{i}]),
        .base(base64[AW-1:0] + {i} * {{17'd0, stride}}), .beats(beats), .burst(burst_r[8:0]), .step(step_r),
        .maxout(maxout_r[7:0]), .nids(nids_r[6:0]), .qos(axparam[3:0]), .cache(axparam[7:4]),
        .done(done_v[{i}]), .cycles(cyc_v[{i}]), .rcv_beats(rcv_v[{i}]),
        .err_count(err_v[{i}]), .xsum(xs_v[{i}]),
        .arid(m{i}_axi_arid), .araddr(m{i}_axi_araddr), .arlen(m{i}_axi_arlen),
        .arsize(m{i}_axi_arsize), .arburst(m{i}_axi_arburst), .arlock(m{i}_axi_arlock),
        .arcache(m{i}_axi_arcache), .arprot(m{i}_axi_arprot), .arqos(m{i}_axi_arqos),
        .arvalid(m{i}_axi_arvalid), .arready(m{i}_axi_arready),
        .rid(m{i}_axi_rid), .rdata(m{i}_axi_rdata), .rresp(m{i}_axi_rresp),
        .rlast(m{i}_axi_rlast), .rvalid(m{i}_axi_rvalid), .rready(m{i}_axi_rready));
    assign m{i}_axi_awid = 0;   assign m{i}_axi_awaddr = 0;  assign m{i}_axi_awlen = 0;
    assign m{i}_axi_awsize = 3'b100; assign m{i}_axi_awburst = 2'b01; assign m{i}_axi_awlock = 1'b0;
    assign m{i}_axi_awcache = 4'b0011; assign m{i}_axi_awprot = 3'b000; assign m{i}_axi_awqos = 4'b0;
    assign m{i}_axi_awvalid = 1'b0; assign m{i}_axi_wdata = 128'b0; assign m{i}_axi_wstrb = 16'b0;
    assign m{i}_axi_wlast = 1'b0; assign m{i}_axi_wvalid = 1'b0; assign m{i}_axi_bready = 1'b1;
""")
    a("""    // global go -> all-done cycle counter
    reg        busy;
    reg [63:0] gcyc;
    wire all_done = &(done_v | ~enable);
    always @(posedge clk) begin
        if (rst) begin busy <= 1'b0; gcyc <= 0; end
        else if (go_pulse) begin busy <= 1'b1; gcyc <= 0; end
        else if (busy) begin
            if (all_done) busy <= 1'b0; else gcyc <= gcyc + 64'd1;
        end
    end

    // ---------------- AXI-Lite read ----------------
    reg [C_S_AXI_ADDR_WIDTH-3:0] aridx;
    reg [31:0] rd_mux;
    wire [2:0] sub = aridx[2:0];
    wire [4:0] mi  = aridx[7:3] - 5'd8;   // 0x100 >> 5 = 8
    integer k;
    always @(*) begin
        rd_mux = 32'b0;
        case (aridx)
            8'h01: rd_mux = {15'b0, busy, {(16-NM){1'b0}}, done_v};
            8'h02: rd_mux = enable;
            8'h03: rd_mux = base_lo;   8'h04: rd_mux = base_hi;
            8'h05: rd_mux = stride;    8'h06: rd_mux = beats;
            8'h07: rd_mux = burst_r;   8'h08: rd_mux = maxout_r;
            8'h09: rd_mux = nids_r;
            8'h0A: rd_mux = gcyc[31:0]; 8'h0B: rd_mux = gcyc[63:32];
            8'h0C: rd_mux = 32'h42575052;   // "BWPR"
            8'h0D: rd_mux = NM;
            8'h0E: rd_mux = axparam;
            8'h0F: rd_mux = step_r;
            default: ;
        endcase
        for (k = 0; k < NM; k = k + 1) begin
            if (aridx[7:3] == 8 + k) begin
                case (sub)
                    3'd0: rd_mux = cyc_v[k][31:0];
                    3'd1: rd_mux = cyc_v[k][63:32];
                    3'd2: rd_mux = rcv_v[k];
                    3'd3: rd_mux = err_v[k];
                    3'd4: rd_mux = xs_v[k][31:0];
                    3'd5: rd_mux = xs_v[k][63:32];
                    3'd6: rd_mux = xs_v[k][95:64];
                    3'd7: rd_mux = xs_v[k][127:96];
                endcase
            end
        end
    end

    always @(posedge clk) begin
        if (!aresetn) begin
            S_AXI_ARREADY <= 1'b0; S_AXI_RVALID <= 1'b0; S_AXI_RRESP <= 2'b00;
            S_AXI_RDATA <= 32'b0; aridx <= 0;
        end else begin
            if (S_AXI_ARVALID && !S_AXI_ARREADY && !S_AXI_RVALID) begin
                S_AXI_ARREADY <= 1'b1; aridx <= S_AXI_ARADDR[C_S_AXI_ADDR_WIDTH-1:2];
            end else S_AXI_ARREADY <= 1'b0;
            if (S_AXI_ARREADY) begin
                S_AXI_RVALID <= 1'b1; S_AXI_RRESP <= 2'b00; S_AXI_RDATA <= rd_mux;
            end else if (S_AXI_RVALID && S_AXI_RREADY) begin
                S_AXI_RVALID <= 1'b0;
            end
        end
    end
endmodule""")
    return "\n".join(L) + "\n"


def gen_tb_inst(nm: int) -> str:
    """DUT instance for tb/tb_bwprobe.sv (read channels to the slave models)."""
    L = ["// GENERATED by fabric/big/gen_bwprobe_top.py", "bwprobe_axi dut (",
         "    .S_AXI_ACLK(clk), .S_AXI_ARESETN(aresetn),",
         "    .S_AXI_AWADDR(s_awaddr), .S_AXI_AWPROT(3'b0), .S_AXI_AWVALID(s_awvalid),",
         "    .S_AXI_AWREADY(s_awready), .S_AXI_WDATA(s_wdata), .S_AXI_WSTRB(4'hF),",
         "    .S_AXI_WVALID(s_wvalid), .S_AXI_WREADY(s_wready), .S_AXI_BRESP(s_bresp),",
         "    .S_AXI_BVALID(s_bvalid), .S_AXI_BREADY(s_bready), .S_AXI_ARADDR(s_araddr),",
         "    .S_AXI_ARPROT(3'b0), .S_AXI_ARVALID(s_arvalid), .S_AXI_ARREADY(s_arready),",
         "    .S_AXI_RDATA(s_rdata), .S_AXI_RRESP(s_rresp), .S_AXI_RVALID(s_rvalid),",
         "    .S_AXI_RREADY(s_rready),"]
    conns = []
    for i in range(nm):
        p = f"m{i}_axi_"
        for n in ("arid", "araddr", "arlen", "arsize", "arburst", "arvalid", "arready",
                  "rid", "rdata", "rresp", "rlast", "rvalid", "rready"):
            conns.append(f"    .{p}{n}({n}[{i}])")
        conns += [f"    .{p}awready(1'b0)", f"    .{p}wready(1'b0)",
                  f"    .{p}bid({{6{{1'b0}}}})", f"    .{p}bresp(2'b0)", f"    .{p}bvalid(1'b0)"]
    L.append(",\n".join(conns))
    L.append(");")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nm", type=int, default=6)
    args = ap.parse_args()
    out = HERE / "rtl" / "bwprobe_axi.v"
    out.write_text(gen(args.nm))
    (HERE / "tb" / "tb_bwprobe_inst.svh").write_text(gen_tb_inst(args.nm))
    print(f"wrote {out} + tb/tb_bwprobe_inst.svh (NM={args.nm})")


if __name__ == "__main__":
    main()
